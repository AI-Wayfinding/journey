// Generate the shipped rule modules and their lock in memory. build.ts writes
// the result; check.ts compares it byte for byte with the committed files.
import {createHash} from 'node:crypto'
import {readFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {compileJs} from 'gdp-wired/machine'
import {models} from '../src/models.ts'

export const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(pkgRoot, '..', '..')

const readJson = (path: string): Record<string, any> => JSON.parse(readFileSync(path, 'utf8'))

// The gdp-wired version must be the exact pin in package.json, installed as
// the lockfile records it. A bump changes the lock, so it shows in review.
function gdpWired(): {version: string, integrity: string} {
  const pin = readJson(join(pkgRoot, 'package.json')).dependencies?.['gdp-wired']
  const installed = readJson(join(repoRoot, 'node_modules', 'gdp-wired', 'package.json')).version
  const locked = readJson(join(repoRoot, 'package-lock.json')).packages?.['node_modules/gdp-wired']
  if (typeof pin !== 'string' || !/^\d+\.\d+\.\d+$/.test(pin)) throw new Error(`gdp-wired must be pinned to an exact version, not ${pin}`)
  if (installed !== pin || locked?.version !== pin) throw new Error(`gdp-wired ${pin} is pinned, but ${installed} is installed and ${locked?.version} is locked; run npm ci`)
  if (typeof locked.integrity !== 'string') throw new Error('package-lock.json records no integrity for gdp-wired')
  return {version: pin, integrity: locked.integrity}
}

const declaration = (name: string) => `// Generated by scripts/build.ts for the rule ${name}. Do not edit.
import type {State} from 'gdp-wired/machine'
export declare function init(params: object): State
export declare function fork(state: State): State
export declare function step(params: object, state: State, input: object): State
`

const sha256 = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex')

// Relative path (from the package root) to exact file contents.
export function generate(): Map<string, string> {
  const {version, integrity} = gdpWired()
  const out = new Map<string, string>()
  for (const [name, rule] of Object.entries(models)) {
    const header = `// Generated by scripts/build.ts from src/${name}.ts with gdp-wired ${version} compileJs. Do not edit.\n`
    out.set(`generated/${name}.js`, header + compileJs(rule.machine))
    out.set(`generated/${name}.d.ts`, declaration(name))
  }
  const files = Object.fromEntries([...out].sort(([a], [b]) => (a < b ? -1 : 1)).map(([path, text]) => [path, sha256(text)]))
  out.set('rules.lock.json', JSON.stringify({gdpWired: version, gdpWiredIntegrity: integrity, files}, null, 2) + '\n')
  return out
}
