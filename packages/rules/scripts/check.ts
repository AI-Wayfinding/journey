import {existsSync, readdirSync, readFileSync} from 'node:fs'
import {join} from 'node:path'
import {generate, pkgRoot} from './pipeline.ts'

const out = generate()
const problems: string[] = []
for (const [path, text] of out) {
  const file = join(pkgRoot, path)
  if (!existsSync(file)) problems.push(`${path} is missing`)
  else if (readFileSync(file, 'utf8') !== text) problems.push(`${path} differs from what the build generates`)
}
const dir = join(pkgRoot, 'generated')
for (const name of existsSync(dir) ? readdirSync(dir) : [])
  if (!out.has(`generated/${name}`)) problems.push(`generated/${name} is not generated by any model`)

if (problems.length) {
  for (const p of problems) console.error(p)
  console.error('generated rules are stale: run npm run build:rules and commit the result')
  process.exit(1)
}
console.log(`generated rules up to date (${out.size} files)`)
