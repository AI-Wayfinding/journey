import { test } from 'node:test';
import assert from 'node:assert/strict';
import { MemoryBackend } from '../src/backend.ts';
import { parseCommand } from '../src/commands.ts';
import { installTestAccountIdentity, resignDeviceRegistration } from './account-fixture.ts';
import { authenticator } from './console-authenticator.ts';
const identity={subject:'alice',clientId:'https://poc.wayfinding.support/console/client.json'};
async function fixture(){
  let now=Date.now();
  const backend=new MemoryBackend({async get(s){return {name:s,email:`${s}@example.test`};}},()=>now,undefined,true);
  await backend.execute('alice',parseCommand('account_read',{}),identity.clientId);
  const key=await authenticator(),options=await backend.passkey(identity,{op:'begin'});
  await backend.passkey(identity,{op:'finish',credential:key.register(String(options.challenge))});
  const account=await installTestAccountIdentity(backend,'alice',identity.clientId);
  const signed=await account.device({deviceId:`device_${crypto.randomUUID()}`,data:'AQ=='});
  const fields={browserId:crypto.randomUUID(),credentialId:key.id,device:signed.registration};
  return {backend,key,fields,root:signed.root,advance:()=>{now+=300001;}};
}
test('sealing browser enrollment needs exact fresh passkey binding; origin account replay and no UV refused',async()=>{
  const {backend,key,fields,root,advance}=await fixture();
  const options=await backend.passkey(identity,{op:'browser_begin',...fields});
  const assertion=await key.assert(String(options.challenge));
  const before=backend.snapshot();
  const substituted=await resignDeviceRegistration(root,{...fields.device,data:'Ag=='});
  await assert.rejects(backend.passkey(identity,{op:'browser_finish',...fields,device:substituted,assertion}),/Fresh exact/);
  assert.equal(backend.snapshot(),before);
  await assert.rejects(backend.passkey({...identity,subject:'bob'},{op:'browser_finish',...fields,assertion}),/live person/);
  await assert.rejects(backend.passkey(identity,{op:'browser_finish',...fields,assertion:await key.assert(String(options.challenge),1,'https://evil.test')}),/origin/i);
  await assert.rejects(backend.passkey(identity,{op:'browser_finish',...fields,assertion:await key.assert(String(options.challenge),1,undefined,false)}),/verification|verified/i);
  const binding=await backend.passkey(identity,{op:'browser_finish',...fields,assertion});
  assert.equal(binding.deviceId,fields.device.deviceId);
  await assert.rejects(backend.passkey(identity,{op:'browser_finish',...fields,assertion}),/Fresh exact/);
  const list=await backend.passkey(identity,{op:'browser_list'});
  const browsers=list.browsers as {id:string;credentialId:string;devices:string[];live:boolean;createdAt:number;lastUsedAt:number}[];
  assert.equal(browsers.length,1);const browser=browsers[0]!;
  assert.equal(browser.id,fields.browserId);assert.equal(browser.credentialId,key.id);assert.deepEqual(browser.devices,[fields.device.deviceId]);assert.equal(browser.live,true);assert.ok(browser.createdAt>0);assert.ok(browser.lastUsedAt>=browser.createdAt);
  const survivor=await authenticator(),addition=await backend.passkey(identity,{op:'addition_options'});
  const registration=await backend.passkey(identity,{op:'begin',assertion:await key.assert(String(addition.challenge),2)});
  await backend.passkey(identity,{op:'finish',credential:survivor.register(String(registration.challenge))});
  await assert.rejects(backend.passkey(identity,{op:'delete',id:key.id}),/Revoke browser/);
  const secondDevice=await resignDeviceRegistration(root,{...fields.device,deviceId:`device_${crypto.randomUUID()}`});
  const second={...fields,device:secondDevice};
  const pending=await backend.passkey(identity,{op:'browser_begin',...second});advance();
  await assert.rejects(backend.passkey(identity,{op:'browser_finish',...second,assertion:await key.assert(String(pending.challenge),3)}),/Fresh exact/);
});
