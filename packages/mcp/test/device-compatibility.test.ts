import { test } from 'node:test';
import assert from 'node:assert/strict';
import { MemoryBackend } from '../src/backend.ts';
import { AccountsHost } from '../src/accounts.ts';
import { JourneyHost } from '../src/journey.ts';
import { parseCommand } from '../src/commands.ts';
import { RULES, sameRules, cell } from '../src/rules.ts';
import { cardCaps } from '../src/agents.ts';

const oldCard = 'bcc89603e3ea46b30d1d4acd3f19abf380e652cab1fd195ebfa37b99ae3eb0a3';
const profiles = { async get() { return { name: 'Alice', email: 'alice@example.test' }; } };
test('device.keys compatibility: old card stamp preserves Accounts and Journeys, upgrades on write, never grants new authority', async () => {
  const backend = new MemoryBackend(profiles);
  const account = await backend.execute('alice', parseCommand('account_read', {}));
  const journey = await backend.execute('alice', parseCommand('journey_create', { name: 'Saved journey' }));
  const legacyAccounts = JSON.parse(String(await backend.accountStorage.get('accounts')));
  legacyAccounts.rulesHash.card = oldCard;
  legacyAccounts.accounts[0].agents.push({ id: 'agent_saved', name: 'Saved agent', live: true, card: { scalars: { signed: 1, allowed: 0 }, maps: { Caps: [[3, 1], [20, 1]] } } });
  legacyAccounts.accounts[0].agents.push({ id: 'agent_defaults', name: 'Saved sparse defaults', live: true, card: { scalars: { signed: 1, allowed: 0 }, maps: { Caps: [[0, 0], [20, 1]] }, defaults: { Caps: 1 } } });
  await backend.accountStorage.put('accounts', JSON.stringify(legacyAccounts));
  const storage = backend.journeyStores.get(String(journey.journeyId))!;
  const legacyJourney = JSON.parse(String(await storage.get('journey')));
  legacyJourney.rulesHash.card = oldCard;
  await storage.put('journey', JSON.stringify(legacyJourney));
  const before = backend.snapshot();
  const accounts = new AccountsHost(backend.accountStorage, profiles);
  const saved = (await accounts.lookup('alice'))!;
  assert.equal(saved.personId, account.personId);
  assert.deepEqual(cardCaps(saved.agents[0]!.card), ['read']);
  assert.equal(cell(saved.agents[1]!.card, 'Caps', 0), 0);
  assert.equal(cell(saved.agents[1]!.card, 'Caps', 3), 1, 'old sparse defaults preserve existing permissions');
  assert.equal(cell(saved.agents[1]!.card, 'Caps', 20), 0, 'old defaults cannot grant the new capability');
  const host = new JourneyHost(storage);
  const read = await host.execute(String(account.personId), parseCommand('journey_read', { journeyId: journey.journeyId }));
  assert.equal(read.name, 'Saved journey');
  assert.equal(backend.snapshot(), before, 'compatibility reads do not write');
  await accounts.update(String(account.personId), 'Saved nickname');
  assert.deepEqual(JSON.parse(String(await backend.accountStorage.get('accounts'))).rulesHash, RULES);
  assert.deepEqual(cardCaps((await accounts.lookup('alice'))!.agents[0]!.card), ['read']);
  const upgraded = (await accounts.lookup('alice'))!.agents[1]!.card;
  assert.equal(cell(upgraded, 'Caps', 0), 0);
  assert.equal(cell(upgraded, 'Caps', 3), 1);
  assert.equal(cell(upgraded, 'Caps', 20), 0);
  await host.execute(String(account.personId), parseCommand('journey_policy', { journeyId: journey.journeyId, policy: 'open', defaultRole: 'write' }));
  assert.deepEqual(JSON.parse(String(await storage.get('journey'))).rulesHash, RULES);
  assert.equal(sameRules({ ...RULES, card: 'unknown' }), false);
  assert.equal(sameRules({ ...RULES, card: oldCard, journey: 'unknown' }), false);
});
