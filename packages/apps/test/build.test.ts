import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { generate, run } from '../scripts/build.ts';
import { releasedViews } from '../generated/views.ts';

test('apps build: generated bytes are current and check/build do not rewrite matching files', async () => {
  const path = new URL('../generated/views.ts', import.meta.url);
  const original = await readFile(path, 'utf8');
  const before = await stat(path);
  assert.equal(await generate(), original);
  await run(true);
  await run(false);
  assert.equal((await stat(path)).mtimeMs, before.mtimeMs);
  assert.equal(await readFile(path, 'utf8'), original);
});

test('apps build: released resources are complete inline HTML without external scripts or fetch', () => {
  assert.deepEqual(releasedViews.map((view) => view.uri).sort(), [
    'ui://wayfinding/v1/artifacts.html', 'ui://wayfinding/v1/journey.html', 'ui://wayfinding/v1/project.html',
    'ui://wayfinding/v2/forum.html',
  ]);
  for (const view of releasedViews) {
    assert.match(view.html, /^<!doctype html>/);
    assert.match(view.html, /Your conversation goes to your AI provider/);
    assert.match(view.html, /<style>[\s\S]+<\/style>/);
    assert.match(view.html, /<script>[\s\S]+<\/script>/);
    assert.doesNotMatch(view.html, /<(?:script|link)[^>]+(?:src|href)=/i);
  }
});
