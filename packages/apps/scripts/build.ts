import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { viewKinds } from '../src/contract.ts';

const root = new URL('../', import.meta.url);
export async function generate(): Promise<string> {
  const bundle = await build({ entryPoints: [fileURLToPath(new URL('src/view.ts', root))], bundle: true,
    write: false, format: 'iife', platform: 'browser', target: 'es2022', minify: true, legalComments: 'inline' });
  const script = bundle.outputFiles[0]!.text.replaceAll('</script', '<\\/script');
  const style = await readFile(new URL('src/style.css', root), 'utf8');
  const releases = await Promise.all(viewKinds.map(async (kind) => {
    const body = await readFile(new URL(`src/${kind}.html`, root), 'utf8');
    const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Wayfinding ${kind}</title><style>${style}</style></head><body data-view="${kind}"><p role="note">Your conversation goes to your AI provider. This view shows coordination metadata only, never artifact content.</p>${body}<p id="status" role="status">Connecting to your AI host…</p><script>${script}</script></body></html>`;
    return { uri: `ui://wayfinding/v1/${kind}.html`, kind, html };
  }));
  return `// Generated by packages/apps/scripts/build.ts. Do not edit.\n// Keep released URI entries when adding a new version.\nexport const releasedViews = ${JSON.stringify(releases)} as const;\n`;
}
export async function run(check: boolean): Promise<void> {
  const destination = new URL('generated/views.ts', root);
  const next = await generate();
  let previous: string | undefined;
  try { previous = await readFile(destination, 'utf8'); }
  catch (error) { if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error; }
  if (previous === next) return;
  if (check) throw new Error('Apps generated views are stale. Run npm run build:apps.');
  await mkdir(new URL('generated/', root), { recursive: true });
  await writeFile(destination, next);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await run(process.argv.includes('--check'));
